console.log(++a + +b++ + +c++ - +a++);
/*
    النتيجة: 100
    الشرح المفصل لكل جزء:
    [++a]   => Pre-increment: يضيف 1 للمتغير أولاً ثم يطبعه. (a تصبح 11)
    [+]     => علامة الجمع (Addition Operator).
    [+b++]  => Unary Plus: يحول النص "20" لرقم، ثم Post-increment: يطبع 20 ثم يضيف 1. (b تصبح 21)
    [+]     => علامة الجمع.
    [+c++]  => Unary Plus & Post-increment: يطبع 80 ثم يضيف 1. (c تصبح 81)
    [-]     => علامة الطرح (Subtraction Operator).
    [+a++]  => Unary Plus & Post-increment: يطبع قيمة a الحالية (11) ثم يضيف 1. (a تصبح 12)
    المعادلة النهائية: 11 + 20 + 80 - 11 = 100
*/

// ================= السطر الثاني =================
console.log(++a + -b + +c++ - -a++ + +a);
    /*
    النتيجة: 100
    (القيم الحالية: a=12, b=21, c=81)
    [++a]   => Pre-increment: (a تصبح 13)
    [+]     => علامة الجمع.
    [-b]    => Unary Negation: يعكس إشارة القيمة. (النتيجة: -21)
    [+]     => علامة الجمع.
    [+c++]  => Unary Plus & Post-increment: يطبع القيمة الحالية (81) ثم يضيف 1. (c تصبح 82)
    [-]     => علامة الطرح.
    [-a++]  => Unary Negation & Post-increment: يعكس إشارة القيمة (-13) ثم يضيف 1 لـ a. (a تصبح 14)
    [+]     => علامة الجمع.
    [+a]    => Unary Plus: يطبع القيمة الحالية لـ a. (النتيجة: 14)
    المعادلة النهائية: 13 + -21 + 81 - -13 + 14 = 100
    */

// ================= السطر الثالث =================
console.log(--c + +b + --a * +b++ - +b * a + --a - +true);
    /*
    النتيجة: 100
    (القيم الحالية: a=14, b=21, c=82)
    [--c]   => Pre-decrement: ينقص 1 ثم يطبع. (c تصبح 81)
    [+]     => علامة الجمع.
    [+b]    => Unary Plus: يطبع قيمة b وهي 21.
    [+]     => علامة الجمع.
    [--a]   => Pre-decrement: ينقص 1. (a تصبح 13)
    [*]     => علامة الضرب.
    [+b++]  => Unary Plus & Post-increment: يطبع 21 ثم يضيف 1. (b تصبح 22)
    [-]     => علامة الطرح.
    [+b]    => Unary Plus: قيمة b الجديدة (22).
    [*]     => علامة الضرب.
    [a]     => المتغير a وقيمته الحالية (13).
    [+]     => علامة الجمع.
    [--a]   => Pre-decrement: ينقص 1. (a تصبح 12)
    [-]     => علامة الطرح.
    [+true] => Unary Plus: يحول الـ true إلى رقم (1).
    
    المعادلة النهائية مع مراعاة أولويات العمليات الحسابية (الضرب أولاً):
    81 + 21 + (13 * 21) - (22 * 13) + 12 - 1
    81 + 21 + 273 - 286 + 12 - 1 = 100
    */

let d = "-100";
let e = "20";
let f = 30;
let g = true;

// 1. الهدف: طباعة الرقم 2000 باستخدام d و e فقط
console.log(-d * e); // 2000
// التفسير: استخدام Unary Negation (-d) سيحول "-100" إلى 100 موجب.
// ثم نضربها في e (وهي 20) = 2000.

// 2. الهدف: طباعة الرقم 173 باستخدام كل المتغيرات (دون تكرار المتغير في السطر)
console.log(++e * ++g + ++f + -d); // 173
/*
    التفسير: 
    ++e => يضيف 1 ويحولها لرقم فتصبح (21)
    ++g => يضيف 1 للـ true فتصبح (2) 
    ++f => يضيف 1 فتصبح (31)
    -d  => يعكس الإشارة فيصبح (100 موجب)
    المعادلة: (21 * 2) + 31 + 100 = 42 + 31 + 100 = 173
*/