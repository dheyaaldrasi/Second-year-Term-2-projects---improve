/* دفتر مستقل لحركة الغاز داخل الخزان؛ CURRENT_LEVEL رصيد مخزن مشتق */
CREATE TABLE TANK_MOVEMENT (
    TANK_MOVEMENT_ID       NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    COMPANY_ID             NUMBER(19) NOT NULL,
    TANK_ID                NUMBER(19) NOT NULL,
    MOVEMENT_NUMBER        VARCHAR2(40 CHAR) NOT NULL,
    MOVEMENT_DATE          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    MOVEMENT_TYPE          VARCHAR2(20 CHAR) NOT NULL,
    QUANTITY_IN            NUMBER(20,3) DEFAULT 0 NOT NULL,
    QUANTITY_OUT           NUMBER(20,3) DEFAULT 0 NOT NULL,
    UNIT_ID                NUMBER(19) NOT NULL,
    UNIT_COST              NUMBER(20,6) DEFAULT 0 NOT NULL,
    PURCHASE_INVOICE_ITEM_ID NUMBER(19),
    FILLING_ITEM_ID        NUMBER(19),
    STOCK_ADJUSTMENT_ITEM_ID NUMBER(19),
    STATUS                 VARCHAR2(15 CHAR) DEFAULT 'DRAFT' NOT NULL,
    CREATED_BY             NUMBER(19),
    POSTED_BY              NUMBER(19),
    POSTED_AT              TIMESTAMP(6),
    NOTES                  VARCHAR2(400 CHAR),
    CONSTRAINT PK_TANK_MOVEMENT PRIMARY KEY (TANK_MOVEMENT_ID),
    CONSTRAINT UQ_TANK_MOV_NO UNIQUE (COMPANY_ID, MOVEMENT_NUMBER),
    CONSTRAINT FK_TM_TANK FOREIGN KEY (COMPANY_ID, TANK_ID)
        REFERENCES STORAGE_TANK (COMPANY_ID, TANK_ID),
    CONSTRAINT FK_TM_UNIT FOREIGN KEY (UNIT_ID)
        REFERENCES UNIT_OF_MEASURE (UNIT_ID),
    CONSTRAINT FK_TM_PURCHASE FOREIGN KEY (COMPANY_ID, PURCHASE_INVOICE_ITEM_ID)
        REFERENCES PURCHASE_INVOICE_ITEM (COMPANY_ID, PURCHASE_INVOICE_ITEM_ID),
    CONSTRAINT FK_TM_FILL FOREIGN KEY (COMPANY_ID, FILLING_ITEM_ID)
        REFERENCES GAS_FILLING_OPERATION_ITEM (COMPANY_ID, FILLING_ITEM_ID),
    CONSTRAINT FK_TM_ADJUST FOREIGN KEY (COMPANY_ID, STOCK_ADJUSTMENT_ITEM_ID)
        REFERENCES STOCK_ADJUSTMENT_ITEM (COMPANY_ID, STOCK_ADJUSTMENT_ITEM_ID),
    CONSTRAINT FK_TM_CREATOR FOREIGN KEY (CREATED_BY)
        REFERENCES APP_USER (APP_USER_ID) ON DELETE SET NULL,
    CONSTRAINT FK_TM_POSTER FOREIGN KEY (POSTED_BY)
        REFERENCES APP_USER (APP_USER_ID) ON DELETE SET NULL,
    CONSTRAINT CK_TM_TYPE CHECK (MOVEMENT_TYPE IN ('RECEIPT','CONSUMPTION','ADJUSTMENT_IN','ADJUSTMENT_OUT')),
    CONSTRAINT CK_TM_QTY CHECK
        ((QUANTITY_IN > 0 AND QUANTITY_OUT = 0) OR (QUANTITY_OUT > 0 AND QUANTITY_IN = 0)),
    CONSTRAINT CK_TM_COST CHECK (UNIT_COST >= 0),
    CONSTRAINT CK_TM_SOURCE CHECK
        ((CASE WHEN PURCHASE_INVOICE_ITEM_ID IS NOT NULL THEN 1 ELSE 0 END) +
            (CASE WHEN FILLING_ITEM_ID IS NOT NULL THEN 1 ELSE 0 END) +
            (CASE WHEN STOCK_ADJUSTMENT_ITEM_ID IS NOT NULL THEN 1 ELSE 0 END) = 1),
    CONSTRAINT CK_TM_DIRECTION CHECK
        ((MOVEMENT_TYPE IN ('RECEIPT','ADJUSTMENT_IN') AND QUANTITY_IN > 0 AND QUANTITY_OUT = 0) OR
            (MOVEMENT_TYPE IN ('CONSUMPTION','ADJUSTMENT_OUT') AND QUANTITY_OUT > 0 AND QUANTITY_IN = 0)),
    CONSTRAINT CK_TM_STATUS CHECK (STATUS IN ('DRAFT','POSTED','VOID')),
    CONSTRAINT CK_TM_POSTED CHECK (STATUS <> 'POSTED' OR (POSTED_AT IS NOT NULL AND POSTED_BY IS NOT NULL))
);



